r"""Measure the research-only ``Variant`` fields and choice values.

    python tools/research_fields.py              # print the measured lists
    python tools/research_fields.py --write      # rewrite config.py's generated block
    python tools/research_fields.py --check      # exit 1 if config.py is out of date
    python tools/research_fields.py --changelog  # the CHANGELOG's Deprecated entry

A ``Variant`` field is *research-only* when no shipped configuration sets it to a
value other than its default, unless it is a documented user setting
(``PUBLIC_FIELDS``: the anytime mode's knobs, described in ``docs/ANYTIME.md``).
The shipped configurations are every preset (``c23``-``c46``), ``ATMConfig()``,
``ATMConfig.composite()`` and the ``anytime=True`` form of ``c46``
(``minimize(..., anytime=True)``). A *choice
value* is research-only when its field is used by a shipped configuration but no
shipped configuration uses that value (the default value never is). The lists are
measured, not chosen: ``tests/test_research_fields.py`` checks that the block in
``config.py`` is what this script writes. Release 0.6.0 deprecates them
(``FutureWarning``) and 0.7.0 removes them (``CONTRIBUTING.md``, deprecation policy).
"""

from __future__ import annotations

import argparse
import dataclasses
import sys
import textwrap
import warnings
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "src" / "amm_optimizer" / "config.py"
BEGIN = "# BEGIN research fields (generated by tools/research_fields.py; do not edit)\n"
END = "# END research fields\n"

# Documented user settings that no preset changes: never deprecated.
PUBLIC_FIELDS = ("anytime_start_per_dim", "anytime_factor", "anytime_switch")

if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from amm_optimizer import presets  # noqa: E402
from amm_optimizer.config import CHOICES, ATMConfig, Variant  # noqa: E402


def preset_names() -> tuple[str, ...]:
    """Every preset, including any that ``names()`` leaves off its short list."""
    try:
        return tuple(presets.names(research=True))
    except TypeError:
        return tuple(presets.names())


def shipped_configs() -> dict[str, ATMConfig]:
    """The configurations that ship, by name."""
    with warnings.catch_warnings():
        # a stale block in config.py would warn here; the measurement must not care
        warnings.simplefilter("ignore", FutureWarning)
        out = {name: presets.get(name) for name in preset_names()}
        out["ATMConfig()"] = ATMConfig()
        out["composite"] = ATMConfig.composite()
        c46 = presets.get("c46")
        out["c46 anytime"] = dataclasses.replace(
            c46, variant=dataclasses.replace(c46.variant, anytime="replay")
        )
    return out


def measure() -> tuple[tuple[str, ...], dict[str, tuple[str, ...]]]:
    """``(research fields, {used field: its research-only values})``, in field order."""
    defaults = {f.name: f.default for f in dataclasses.fields(Variant)}
    used: dict[str, set[Any]] = {name: set() for name in defaults}
    for config in shipped_configs().values():
        for name, default in defaults.items():
            value = getattr(config.variant, name)
            if value != default:
                used[name].add(value)
    fields = tuple(
        name for name in defaults if not used[name] and name not in PUBLIC_FIELDS
    )
    choices = {
        name: tuple(v for v in allowed[1:] if v not in used[name])
        for name, allowed in CHOICES.items()
        if used[name]
    }
    return fields, {name: values for name, values in choices.items() if values}


def render(fields: tuple[str, ...], choices: dict[str, tuple[str, ...]]) -> str:
    """The generated block of ``config.py``."""
    lines = [BEGIN]
    lines.append(
        "# ``Variant`` fields that no shipped configuration sets (deprecated in "
        "0.6.0).\n"
    )
    lines.append("RESEARCH_FIELDS: tuple[str, ...] = (\n")
    lines += [f'    "{name}",\n' for name in fields]
    lines.append(")\n")
    lines.append(
        "# Values of the shipped string fields that no shipped configuration uses.\n"
    )
    lines.append("RESEARCH_CHOICES: dict[str, tuple[str, ...]] = {\n")
    for name, values in choices.items():
        if len(values) == 1:  # as ``ruff format`` writes it
            lines.append(f'    "{name}": ("{values[0]}",),\n')
            continue
        lines.append(f'    "{name}": (\n')
        lines += [f'        "{v}",\n' for v in values]
        lines.append("    ),\n")
    lines.append("}\n")
    lines.append(END)
    return "".join(lines)


def current_block(text: str) -> str:
    start = text.index(BEGIN)
    end = text.index(END, start) + len(END)
    return text[start:end]


def changelog(fields: tuple[str, ...], choices: dict[str, tuple[str, ...]]) -> str:
    """The ``### Deprecated`` entry of the CHANGELOG (Markdown)."""
    names = ", ".join(f"`{name}`" for name in fields)
    values = "; ".join(
        f"`{name}` " + ", ".join(f'`"{v}"`' for v in vals)
        for name, vals in choices.items()
    )
    text = (
        f"- **{len(fields)} research-only `Variant` fields and "
        f"{sum(map(len, choices.values()))} research-only values of the other "
        "fields** emit a `FutureWarning` when set and will be removed in 0.7.0 "
        '(`warnings.filterwarnings("ignore", "Variant", FutureWarning)` silences '
        "them meanwhile). No shipped "
        "configuration (`c23`-`c46`, `ATMConfig()`, `ATMConfig.composite()`, "
        "`anytime=True`) uses them, so none of those warns, and their config hashes "
        "and results are unchanged. The lists are `config.RESEARCH_FIELDS` and "
        "`config.RESEARCH_CHOICES`, measured by `tools/research_fields.py`. "
        f"Fields: {names}. Values: {values}."
    )
    return textwrap.fill(text, width=95, subsequent_indent="  ") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    group.add_argument("--changelog", action="store_true")
    args = parser.parse_args()
    fields, choices = measure()
    block = render(fields, choices)
    if args.changelog:
        print(changelog(fields, choices), end="")
        return 0
    if args.write or args.check:
        text = CONFIG.read_text(encoding="utf8")
        if args.check:
            ok = current_block(text) == block
            print("config.py is up to date" if ok else "config.py is out of date")
            return 0 if ok else 1
        CONFIG.write_bytes(text.replace(current_block(text), block).encode("utf8"))
        print(f"wrote {len(fields)} fields and {len(choices)} choice fields")
        return 0
    print(f"{len(fields)} research-only fields:")
    print("  " + "\n  ".join(fields))
    count = sum(map(len, choices.values()))
    print(f"{count} research-only values of {len(choices)} shipped fields:")
    for name, values in choices.items():
        print(f"  {name}: {', '.join(values)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
