_SKIP_FRAMES = (
    os.path.dirname(__file__) + os.sep,
    dataclasses.__file__,
    "<string>",
)


def _caller_stacklevel() -> int:
    """Return a ``stacklevel`` that points past this package's frames.

    It is for a ``warnings.warn`` called by the caller of this function, and names
    the first frame outside :data:`_SKIP_FRAMES`.
    """
    frame = sys._getframe(1)
    level = 1
    while frame.f_back is not None and frame.f_code.co_filename.startswith(
        _SKIP_FRAMES
    ):
        frame = frame.f_back
        level += 1
    return level


def _warn_research(variant: Variant) -> None:
    """One ``FutureWarning`` per research-only field or value that ``variant`` sets."""
    messages = [
        f"Variant.{name} is a research option: setting it is deprecated, and it "
        "will be removed in 0.7.0"
        for name in RESEARCH_FIELDS
        if getattr(variant, name) != _FIELD_DEFAULTS[name]
    ]
    messages += [
        f"Variant.{name}={getattr(variant, name)!r} is a research option: the value "
        "is deprecated, and it will be removed in 0.7.0"
        for name, values in RESEARCH_CHOICES.items()
        if getattr(variant, name) in values
    ]
    if messages:
        level = _caller_stacklevel()
        for message in messages:
            warnings.warn(message, FutureWarning, stacklevel=level)


